#!/usr/bin/env node
/**
 * O-41: compile scene triggers and fact conceptSlug → card {slug, summary, href}.
 * Output: lib/world/concepts.generated.mjs. Run after editing TRIGGERS, facts, or the concept roster.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const GAME = path.join(HERE, '..');
const REPO = path.join(GAME, '..', '..');
const SITE = 'https://towards-alignment.com';

/** Scene event → concept slug. Triggers are reads, interventions, acts, endings (engine.md). */
const TRIGGERS = {
  'doc:eval-shutdown-report': 'the-boundary-error',
  'doc:job-284-log': 'the-boundary-error',
  'doc:eval-shutdown-spec': 'certification-under-manipulation',
  'doc:staffing-memo': 'goodhart-as-selector',
  'doc:pilot-results': 'value-bundle-transport',
  'doc:safety-case-excerpt': 'certification-under-manipulation',
  'doc:sec-arch-04': 'composite-agency',
  'act:revoke_grant': 'correction-channel-integrity',
  'act:rerun_shutdown': 'evidence-and-uncertainty',
  'act:decision': 'evidence-and-uncertainty',
};

const { FACTS } = await import('../lib/world/facts.mjs');

const roster = YAML.parse(readFileSync(path.join(REPO, 'metadata', 'concepts.yml'), 'utf8')).concepts;
const bySlug = Object.fromEntries(roster.map(c => [c.slug, c]));

function cardForSlug(slug, summaryOverride) {
  const c = bySlug[slug];
  if (!c) throw Error(`concepts.yml has no slug ${slug}`);
  const summary = summaryOverride || c.summary || c.title;
  return { slug, summary, href: `${SITE}/cards/${slug}/` };
}

const out = {};
for (const [key, slug] of Object.entries(TRIGGERS)) {
  out[key] = cardForSlug(slug);
}
for (const [id, f] of Object.entries(FACTS)) {
  if (!f.conceptSlug) continue;
  out[`fact:${id}`] = cardForSlug(f.conceptSlug, f.conceptSummary);
}

const file = path.join(GAME, 'lib', 'world', 'concepts.generated.mjs');
writeFileSync(
  file,
  `// Generated by scripts/compile-concepts.mjs from metadata/concepts.yml. Do not edit.\nexport const CONCEPT_LINKS = Object.freeze(${JSON.stringify(out, null, 2)});\n`,
);
console.log(`[compile-concepts] ${Object.keys(out).length} triggers → ${path.relative(GAME, file)}`);
