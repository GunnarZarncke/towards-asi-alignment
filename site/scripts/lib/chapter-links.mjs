// Chapter / appendix labels for field-news footers and the /news/ index.
import { readFile } from "node:fs/promises";
import path from "node:path";

/** Appendix titles — keep in sync with sync-chapter-cards.mjs appendixSpecs. */
export const APPENDIX_TITLES = {
  appB: "Bridges and the Field: A Crosswalk",
  appC: "Human Institutions as Alignment Translation Guide",
  appD: "Worked Example",
  appF: "Research Program",
  appM: "Institutional Genesis, Memory, and Decay: Historical Case Studies",
  appN: "Experimental Evidence: Findings by Line"
};

/** Load chapter titles from site/src/data/book.json (generated by sync:book). */
export async function loadChapterTitles(siteRoot) {
  const bookPath = path.join(siteRoot, "src", "data", "book.json");
  const book = JSON.parse(await readFile(bookPath, "utf8"));
  /** @type {Record<string, string>} */
  const titles = {};
  for (const chapter of book.chapters ?? []) {
    titles[chapter.id] = chapter.title;
  }
  return titles;
}

/** @returns {{ prefix: string, title: string }} */
export function chapterLabel(id, titles) {
  if (id.startsWith("app")) {
    const letter = id.slice(3).toUpperCase();
    return {
      prefix: `Appendix ${letter}`,
      title: APPENDIX_TITLES[id] ?? id
    };
  }
  const num = id.replace(/^ch0?/, "");
  return {
    prefix: `Ch. ${num}`,
    title: titles[id] ?? id
  };
}

function joinReadMoreLinks(links) {
  if (links.length === 0) return "";
  if (links.length === 1) return links[0];
  if (links.length === 2) return `${links[0]}; and ${links[1]}`;
  return `${links.slice(0, -1).join("; ")}; and ${links[links.length - 1]}`;
}

/** Markdown footer for field-news card bodies. */
export function formatReadMoreMarkdown(chapterIds, titles) {
  if (!chapterIds?.length) return "";
  const links = chapterIds.map((id) => {
    const { prefix, title } = chapterLabel(id, titles);
    const segment = /^app/i.test(id) ? "appendix" : "chapter";
    return `[${prefix}, *${title}*](/cards/${segment}/${id.toLowerCase()}/)`;
  });
  return `**Read more in:** ${joinReadMoreLinks(links)}.`;
}

/** Structured refs for the /news/ index page. */
export function buildChapterRefs(chapterIds, titles) {
  return (chapterIds ?? []).map((id) => {
    const { prefix, title } = chapterLabel(id, titles);
    const segment = /^app/i.test(id) ? "appendix" : "chapter";
    return { id, prefix, title, href: `/cards/${segment}/${id.toLowerCase()}/` };
  });
}

/** Remove hand-maintained read-more footers before regenerating from YAML. */
export function stripReadMoreFooter(body) {
  return body.replace(/\n?\*\*Read (?:more )?in(?: the book)?:\*\*[^\n]*/g, "").trimEnd();
}
